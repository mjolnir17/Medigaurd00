import "../styles/insights.css";

export default function Risk({ flags, recs }) {
  return (
    <section className="panel">
      <div>
        <h2>Clinical risk report</h2>
        <p className="muted">Warnings generated by fixed rules applied to the results above.</p>
      </div>
      {flags.length === 0 ? (
        <div className="notice">No risk flags were raised for this model.</div>
      ) : (
        <ul className="flags">
          {flags.map((f, i) => (
            <li key={i}>
              <span className={`chip ${f.level === "high" ? "bad" : "mid"}`}>{f.level}</span>
              <div><strong>{f.condition}</strong><div className="muted">{f.message}</div></div>
            </li>
          ))}
        </ul>
      )}
      <h3>Recommendations</h3>
      <div className="recs">
        {recs.map((r) => (
          <div className="rec" key={r.category}>
            <div className="rec-head">
              <strong>{r.category}</strong>
              <span className={`chip ${r.priority === "high" ? "bad" : "mid"}`}>{r.priority}</span>
            </div>
            <ul>{r.actions.map((a) => <li key={a}>{a}</li>)}</ul>
          </div>
        ))}
      </div>
      <p className="muted">The thresholds behind these rules are heuristic and have not been clinically validated.</p>
    </section>
  );
}
